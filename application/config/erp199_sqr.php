<?php defined('SYSPATH') or die('No direct script access.');

/**
 * Настройки модуля QR-маркировки (erp199_sqr).
 *
 * Модуль связывает информационную систему с физическим миром: наклейка с
 * QR-кодом на изделии, партии, заказе или сотруднике, а тонкий клиент (телефон,
 * терминал, WebView) показывает то, что решил сервер. Поэтому настраивается
 * ровно то, что зависит от площадки, а не от кода:
 *
 *  - `code_prefix` — как выглядят коды наклеек этой организации;
 *  - `media` — куда складывать фото с телефонов и сколько они могут весить;
 *  - `ai` — необязательный помощник распознавания фото (без него модуль
 *    работает: подсказка не появляется, объект заводится вручную);
 *  - `allow_register_from_field` — можно ли заводить объект прямо с телефона
 *    там, где наклейку никто не выпускал. Если выключить, терминал покажет
 *    «наклейка не зарегистрирована» и ничего создавать не будет.
 *
 * @package    Erp199
 * @category   Config
 */
return array(

    // =========================================================================
    //  Наклейки
    // =========================================================================

    // Префикс кода наклейки. Полный код = префикс + 4 символа + «-» + 4 символа,
    // например QR-7F3K-9M2P. Алфавит без 0/O/1/I, чтобы код читался человеком
    // и не путался при ручном вводе, если QR-код повреждён.
    'code_prefix' => 'QR-',

    // Пускать ли сотрудника в поле без выпущенной заранее наклейки: терминал
    // создаст свободный объект (черновик) и привяжет к нему код. Черновик
    // проходит модерацию в админке — в основную номенклатуру он не попадает.
    'allow_register_from_field' => TRUE,

    // =========================================================================
    //  Фотографии
    // =========================================================================

    'media' => array(

        // Каталог на диске. По умолчанию — public_html/uploads/erp199,
        // отдаётся веб-сервером как /uploads/erp199/<год>/<месяц>/…
        'path' => DOCROOT.'uploads/erp199',

        // Максимальный размер одного фото (10 МБ — снимок современного
        // телефона). Больше — уже не улика, а проблема с каналом в поле.
        'max_size' => 10485760,

        // Разрешённые расширения (формат проверяется ещё и по содержимому).
        'extensions' => array('jpg', 'jpeg', 'png', 'webp'),

        // Сколько фото хранить по одной наклейке в выдаче терминала.
        'preview_limit' => 6,
    ),

    // =========================================================================
    //  Распознавание фото (необязательно)
    // =========================================================================

    'ai' => array(

        // Провайдер из application/config/llm.php. Пустая строка или 'local' —
        // локальный контур; запрос уходит только при наличии рабочего провайдера.
        'provider' => 'local',

        // Модель. Пусто — ядро LLM само возьмёт vision-модель провайдера.
        'model' => '',

        // Базовый текст подсказки: что именно вытащить из фотографии.
        'prompt' => 'Ты — приёмщик на производстве. Опиши предмет на фотографии и верни JSON:
{
  "label": "краткое название (до 80 символов)",
  "type": "код типа, если понятен",
  "attributes": {"марка": "…", "модель": "…", "серийный_номер": "…", "состояние": "…"},
  "text": "весь читаемый текст с шильдика/наклейки/маркировки",
  "confidence": 0.0-1.0
}
Если что-то не видно — не выдумывай, оставь поле пустым.',
    ),

    // =========================================================================
    //  Терминал (WebView-страница /qr/scan)
    // =========================================================================

    'terminal' => array(

        // Отправлять координаты вместе со сканом (браузер спросит разрешение).
        'geo' => TRUE,

        // Сколько последних действий показывать на странице наклейки.
        'activity_limit' => 10,

        // Тексты, которые видит сотрудник в поле.
        'unknown_hint' => 'Наклейка не выпущена. Сфотографируйте предмет — заявка уйдёт на модерацию.',

        // Печатать ли на этикетке адрес сканирования (fallback, если камера
        // не читает QR): человек наберёт код руками.
        'print_url' => TRUE,
    ),
);
